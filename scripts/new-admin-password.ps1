<#
.SYNOPSIS
    Generates a strong password for the administrator account and stores it in the .env file.

.DESCRIPTION
    The administrator account (AspNetIdentity:DefaultAdmin) is created by the first start up, and
    its password is a deployment secret, so it is never stored in appsettings.json. This script
    generates a cryptographically random value and writes it to the .env file, which is ignored by
    git and by Docker.

    An existing .env file is updated in place: only the AspNetIdentity__DefaultAdmin__Email and
    AspNetIdentity__DefaultAdmin__Password lines are touched, every other setting is kept.

    An installation whose administrator account still uses the password that earlier releases
    published rotates it to this value at the next start up.

.PARAMETER Path
    Target file. Defaults to the .env file in the repository root.

.PARAMETER Length
    Length of the generated password. The default of 24 characters is longer than the minimum of 12
    characters that the application requires for the administrator account.

.PARAMETER Email
    Email address of the administrator account. Defaults to admin@root.com.

.PARAMETER PassThru
    Returns the generated password instead of writing it to the output stream only.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts/new-admin-password.ps1

.EXAMPLE
    .\scripts\new-admin-password.ps1 -Path C:\deploy\wms\.env -Length 32
#>
[CmdletBinding()]
param(
    [string] $Path,
    [ValidateRange(12, 128)]
    [int] $Length = 24,
    [string] $Email = "admin@root.com",
    [switch] $PassThru
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($Path)) {
    $repoRoot = Split-Path -Parent $PSScriptRoot
    $Path = Join-Path $repoRoot ".env"
}

$Path = [System.IO.Path]::GetFullPath($Path)
$directory = Split-Path -Parent $Path
if (-not (Test-Path -LiteralPath $directory)) {
    throw "The directory '$directory' does not exist."
}

# Unambiguous alphanumeric alphabet: safe inside .env files, shells, YAML, and JSON.
$alphabet = "abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
$passwordChars = [char[]]::new($Length)
$random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
$buffer = [byte[]]::new(1)
$limit = 256 - (256 % $alphabet.Length)
try {
    for ($index = 0; $index -lt $Length; $index++) {
        do {
            $random.GetBytes($buffer)
        } while ($buffer[0] -ge $limit)

        $passwordChars[$index] = $alphabet[$buffer[0] % $alphabet.Length]
    }
}
finally {
    $random.Dispose()
}

$password = -join $passwordChars

$header = @(
    "# Generated by scripts/new-admin-password.ps1 - keep this file out of version control.",
    "# AspNetIdentity__DefaultAdmin__Password overrides the empty password in appsettings.json."
)

$existing = @()
if (Test-Path -LiteralPath $Path) {
    $existing = @(Get-Content -LiteralPath $Path)
}

$lines = New-Object System.Collections.Generic.List[string]

if (-not ($existing -contains $header[0])) {
    $header | ForEach-Object { $lines.Add($_) }
    if ($existing.Count -gt 0) {
        $lines.Add("")
    }
}

$emailReplaced = $false
$passwordReplaced = $false

foreach ($line in $existing) {
    if ($line -match '^\s*(export\s+)?AspNetIdentity__DefaultAdmin__Password\s*=') {
        $lines.Add("AspNetIdentity__DefaultAdmin__Password=$password")
        $passwordReplaced = $true
    }
    elseif ($line -match '^\s*(export\s+)?AspNetIdentity__DefaultAdmin__Email\s*=') {
        $lines.Add("AspNetIdentity__DefaultAdmin__Email=$Email")
        $emailReplaced = $true
    }
    else {
        $lines.Add($line)
    }
}

if (-not $emailReplaced) {
    $lines.Add("AspNetIdentity__DefaultAdmin__Email=$Email")
}

if (-not $passwordReplaced) {
    $lines.Add("AspNetIdentity__DefaultAdmin__Password=$password")
}

[System.IO.File]::WriteAllText($Path, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))

Write-Host "Administrator credentials written to: $Path"
Write-Host "AspNetIdentity__DefaultAdmin__Email=$Email"
Write-Host "AspNetIdentity__DefaultAdmin__Password=$password"
Write-Host "Treat this value as a secret. The account keeps working, but an installation that still"
Write-Host "uses the password of an earlier release replaces it with this value on the next start up."

if ($PassThru) {
    $password
}
