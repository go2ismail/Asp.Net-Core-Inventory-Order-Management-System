<#
.SYNOPSIS
    Generates a random JWT signing key and stores it in the .env file.

.DESCRIPTION
    The signing key (Jwt:Key / Jwt__Key) is a deployment secret, so it is never stored in
    appsettings.json. This script generates a cryptographically random value and writes it to the
    .env file, which is ignored by git and by Docker.

    An existing .env file is updated in place: only the Jwt__Key line is replaced, every other
    setting that the file contains is kept.

.PARAMETER Path
    Target file. Defaults to the .env file in the repository root.

.PARAMETER ByteLength
    Number of random bytes. The default of 48 bytes produces a 64 character key.

.PARAMETER PassThru
    Returns the generated key instead of writing it to the output stream only.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts/new-jwt-key.ps1

.EXAMPLE
    .\scripts\new-jwt-key.ps1 -Path C:\deploy\wms\.env -ByteLength 64
#>
[CmdletBinding()]
param(
    [string] $Path,
    [ValidateRange(32, 128)]
    [int] $ByteLength = 48,
    [switch] $PassThru
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($Path)) {
    $repoRoot = Split-Path -Parent $PSScriptRoot
    $Path = Join-Path $repoRoot ".env"
}

$Path = [System.IO.Path]::GetFullPath($Path)
$directory = Split-Path -Parent $Path
if (-not (Test-Path -LiteralPath $directory)) {
    throw "The directory '$directory' does not exist."
}

$keyBytes = [byte[]]::new($ByteLength)
$random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
try {
    $random.GetBytes($keyBytes)
}
finally {
    $random.Dispose()
}

# Base64url: safe inside .env files, shells, YAML, and HTTP headers.
$key = [Convert]::ToBase64String($keyBytes).Replace('+', '-').Replace('/', '_').TrimEnd('=')

$header = @(
    "# Generated by scripts/new-jwt-key.ps1 - keep this file out of version control.",
    "# Jwt__Key overrides Jwt:Key from appsettings.json for local development and Docker Compose."
)

$existing = @()
if (Test-Path -LiteralPath $Path) {
    $existing = @(Get-Content -LiteralPath $Path)
}

$lines = New-Object System.Collections.Generic.List[string]

if (-not ($existing -contains $header[0])) {
    $header | ForEach-Object { $lines.Add($_) }
    if ($existing.Count -gt 0) {
        $lines.Add("")
    }
}

$replaced = $false
foreach ($line in $existing) {
    if ($line -match '^\s*(export\s+)?Jwt__Key\s*=') {
        $lines.Add("Jwt__Key=$key")
        $replaced = $true
    }
    else {
        $lines.Add($line)
    }
}

if (-not $replaced) {
    $lines.Add("Jwt__Key=$key")
}

[System.IO.File]::WriteAllText($Path, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))

Write-Host "JWT signing key written to: $Path"
Write-Host "Jwt__Key=$key"
Write-Host "Treat this value as a secret. Change it per environment, and rotate it if it leaks:"
Write-Host "rotating the key signs out every user because previously issued access tokens stop validating."

if ($PassThru) {
    $key
}
